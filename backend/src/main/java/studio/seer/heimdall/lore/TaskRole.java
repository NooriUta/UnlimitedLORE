package studio.seer.heimdall.lore;

import java.util.List;
import java.util.Set;

/**
 * Роли на задаче и правила, которым они подчиняются (ADR-LORE-042).
 *
 * <p>Вынесено отдельным классом, а не набором строк по месту использования:
 * ровно так — свободной строкой в поле — и накопились 73 написания на десять
 * заявленных личностей. Правило, живущее в одном месте, можно проверить;
 * правило, повторённое в пяти, расходится и молчит об этом.
 */
final class TaskRole {

    private TaskRole() {}

    /** Кто поставил задачу. */
    static final String AUTHOR = "author";
    /** Кто её делает. */
    static final String EXECUTOR = "executor";
    /** Кто ОЦЕНИЛ сделанное и может вернуть. */
    static final String REVIEWER = "reviewer";
    /** Кто принял работу К ПРОДОЛЖЕНИЮ, ничего не оценивая. */
    static final String HANDOFF = "handoff";

    static final List<String> ALL = List.of(AUTHOR, EXECUTOR, REVIEWER, HANDOFF);

    /**
     * Роли, у которых активное ребро может быть только ОДНО.
     *
     * <p>Требование владельца: «проверку, чтобы не было толпы исполнителей по
     * одной таске». У автора один по природе, у исполнителя — потому что «двое
     * делают» на практике означает, что не делает никто конкретный.
     *
     * <p>Ревьюеров и следующих по маршруту законно несколько: ревью бывает
     * двойным, маршрут — цепочкой. Но ДУБЛЬ одной личности в одной роли
     * отвергается для всех четырёх: это не «двое», это повторная запись.
     */
    static final Set<String> SINGLE_HOLDER = Set.of(AUTHOR, EXECUTOR);

    /**
     * Роли, у которых бывает вердикт и отзыв.
     *
     * <p>Только ревьюер. У {@link #HANDOFF} вердикта нет и быть не может — он
     * ничего не оценивал, он взял работу дальше. Разрешить ему вердикт значило
     * бы вернуть ту самую склейку, ради разведения которой роль и появилась.
     */
    static boolean canGiveVerdict(String role) {
        return REVIEWER.equals(role);
    }

    /**
     * Отказ с ПЕРЕЧИСЛЕНИЕМ допустимых значений.
     *
     * <p>Не «недопустимая роль», а какие бывают. Отказ, не называющий
     * альтернатив, заставляет вызывающего угадывать — и он угадает, как
     * угадывал 73 раза в свободном поле.
     */
    static String roleError(String given) {
        return "role='" + given + "' не бывает. Допустимо: " + String.join(" | ", ALL)
            + ". Различайте reviewer и handoff: reviewer ОЦЕНИЛ работу и может её вернуть, "
            + "handoff принял её к продолжению и ничего не оценивал — засчитывать второе "
            + "за первое значит закрывать приёмку фактом, к проверке отношения не имеющим.";
    }

    /**
     * Отказ при попытке назначить второго держателя однодержательной роли.
     *
     * <p>Называет того, кто уже назначен: без этого вызывающий не поймёт,
     * ошибся он или гонка, и повторит попытку.
     */
    static String singleHolderError(String role, String taskUid, String current) {
        return "у задачи " + taskUid + " роль '" + role + "' уже занята: " + current
            + ". Одновременно держатель может быть только один — сначала снимите текущего "
            + "(смена закрывает прежнее ребро, а не стирает его), потом назначайте нового.";
    }

    /**
     * Отказ при незаявленной личности — с перечислением кандидатов.
     *
     * <p>Решение владельца: агент узнаёт, кого ставить, сверяясь с ролями в
     * проекте. Поэтому отказ обязан отдать этот список, а не только сказать
     * «не найдено»: список выводится из графа и вызывающему неизвестен.
     */
    static String unknownIdentityError(String given, List<String> candidates) {
        if (candidates.isEmpty()) {
            return "личность '" + given + "' не заявлена, и предложить некого: в проекте этой "
                + "задачи НЕТ НИ ОДНОЙ роли. Это чинится выдачей роли в админке "
                + "(Люди → карточка → роль в проекте), а не другим написанием имени. "
                + "Проекты без единой роли видны срезом projects_without_role.";
        }
        return "личность '" + given + "' не заявлена. Допустимы: " + String.join(", ", candidates)
            + " — люди с ролью в проекте этой задачи и заявленные агентные личности.";
    }
}
