package studio.seer.heimdall.lore.llm;

/**
 * Один поставщик языковой модели за общим интерфейсом.
 *
 * <p>Форма взята у MIMIR (ADR-MIMIR-001, ярус 1): единая точка входа
 * {@link ModelRouter}, за ней сервисы-провайдеры под одним интерфейсом. Второй
 * образец маршрутизации моделей в корпусе заводить не стали намеренно — это был
 * бы второй словарь там, где мы весь спринт сводим первый.
 *
 * <h2>Чем наш случай отличается от MIMIR</h2>
 * У MIMIR модель выбирает клиент на каждый запрос: человек спрашивает разное.
 * У нас модель — <b>настройка владельца</b>: прогон гейта обязан быть
 * воспроизводим, а смена модели должна быть осознанным действием, видимым в
 * ряду как разрыв (SPEC-QG-ARCHITECTURE §9), а не случайностью очередного вызова.
 *
 * <h2>Обязанность реализации</h2>
 * Провайдер <b>никогда не бросает</b> при недоступности внешнего сервиса и
 * никогда не возвращает пустой ответ вместо отказа. Недоступность, таймаут,
 * неверный ключ, отсутствующая модель — всё это
 * {@link LlmAnswer#unavailable(String)} с названной причиной. Исключения
 * остаются только для дефектов программиста.
 */
public interface LlmProvider {

    /**
     * Имя, под которым провайдер выбирается настройкой владельца.
     * Стабильное и человекочитаемое: оно попадёт в запись прогона и в интерфейс.
     */
    String name();

    /**
     * Настроен ли провайдер к работе — есть ли адрес, ключ, имя модели.
     *
     * <p>Отвечает на вопрос «можно ли пытаться», а не «ответит ли сейчас»:
     * живость внешнего сервиса проверяется самим вызовом, потому что проверять
     * её заранее значит делать два запроса вместо одного и всё равно не иметь
     * гарантии к моменту второго.
     */
    boolean configured();

    /**
     * Причина, по которой провайдер не настроен. Осмысленна только когда
     * {@link #configured()} ложно, и обязана называть недостающее — «не настроен»
     * без указания чего именно не хватает отправляет читателя в исходники.
     */
    String misconfigurationReason();

    /**
     * Спросить модель. Возвращает ответ либо явную недоступность; не бросает
     * при отказе внешнего сервиса.
     */
    LlmAnswer ask(LlmRequest request);
}
