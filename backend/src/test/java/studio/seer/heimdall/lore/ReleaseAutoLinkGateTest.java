package studio.seer.heimdall.lore;

import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * SE-09: слияние НЕ цепляет PR к уже выпущенному релизу — чистая функция,
 * без Forgejo и без сети, по образцу {@link ForgejoGateStatusTest}.
 *
 * <p><b>Что было.</b> После слияния PR привязывался к релизу с пометкой
 * «текущий», и никто не спрашивал, вышел ли тот. 10.09.2026 — шесть слияний
 * подряд, шесть привязок к v1.10.0, у которого тег уже стоял на main;
 * 31.08 — ещё семь. Правки, влитые в develop после тега, в него физически не
 * входят, а привязка утверждала обратное. Признак богаче состояния, и по нему
 * делается неверный вывод.
 *
 * <p><b>Почему признак — тег в РЕПОЗИТОРИИ, а не поле тега у релиза.</b> План
 * релиза может нести имя тега заранее. Правило «поле тега заполнено — не
 * цеплять» отказало бы ровно там, где цеплять надо: у ещё не вырезанного
 * релиза. Поле может опережать факт; репозиторий — нет.
 *
 * <p><b>Главная проверка здесь — положительный контроль.</b> Невыпущенный
 * релиз обязан по-прежнему получать привязку. Без этого правка, вообще
 * выключившая автопривязку, прошла бы все остальные проверки и выглядела бы
 * так же, как правильная.
 */
class ReleaseAutoLinkGateTest {

    // ── положительный контроль: невыпущенный релиз привязывается ────────────

    @Test
    void aReleaseWithoutATagIsNotShippedAndGetsLinked() {
        var d = ForgejoBridge.autoLinkDecision(null, null);
        assertTrue(d.link(), "у релиза нет тега — он ещё не вышел, привязка обязана встать");
    }

    @Test
    void aTagNameReservedByThePlanButNotCutStillGetsLinked() {
        // Имя тега записано в план, но в репозитории такого тега нет (404).
        // Это и есть случай, ради которого признаком выбран репозиторий, а не
        // поле: по полю этот релиз ошибочно сочли бы выпущенным.
        var d = ForgejoBridge.autoLinkDecision("v1.11.0", 404);
        assertTrue(d.link(), "тег только запланирован — релиз не вышел, привязка обязана встать");
    }

    // ── основное: выпущенный релиз не получает чужих правок ─────────────────

    @Test
    void aShippedReleaseDoesNotReceiveTheLink() {
        // Ровно случай 10.09: тег v1.10.0 существует в репозитории.
        var d = ForgejoBridge.autoLinkDecision("v1.10.0", 200);
        assertFalse(d.link(), "тег стоит в репозитории — релиз вышел, чужую правку к нему не цеплять");
        assertTrue(d.reason().contains("v1.10.0"),
            "причина обязана НАЗЫВАТЬ релиз, иначе пропуск неотличим от поломки инструмента");
    }

    // ── неизвестность: не цеплять и сказать почему ──────────────────────────

    @Test
    void whenTheTagCannotBeCheckedTheLinkIsWithheldAndSaidSo() {
        // Проверка не удалась (сеть, таймаут). Неверная привязка хуже
        // отсутствующей: отсутствие видно и чинится, неверная выглядит
        // сделанной работой.
        var d = ForgejoBridge.autoLinkDecision("v1.10.0", null);
        assertFalse(d.link(), "не сумев проверить, цеплять нельзя");
        assertFalse(d.reason().isBlank(), "молчаливый пропуск неотличим от поломки — причина обязательна");
    }

    @Test
    void anUpstreamErrorCountsAsUnknownNotAsNotShipped() {
        // 5xx — это «не знаем», а НЕ «тега нет». Спутать их значило бы
        // привязать к выпущенному релизу ровно тогда, когда Forgejo прилёг.
        var d = ForgejoBridge.autoLinkDecision("v1.10.0", 502);
        assertFalse(d.link(), "ошибка Forgejo — не доказательство отсутствия тега");
    }
}
