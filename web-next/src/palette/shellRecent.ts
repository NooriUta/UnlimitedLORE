// «Недавнее» палитры — тот же список, что в меню (SPRINT_UXR_S4_UI_SHELL_LISTS/S4-14).
//
// Аудит 08.11 нашёл обе половины этой беды по отдельности: «"Недавние" в левом
// меню пусто даже после открытия записи» (закрыто в PR #941) и «содержимое
// палитры: "Недавних пока нет"». Вторая половина осталась: палитра ведёт СВОЙ
// список недавних, в своём ключе хранилища, и он наполняется только тем, что
// открыли через саму палитру. Человек открывает записи из списка — палитра об
// этом не знает и показывает «пока нет».
//
// Два списка недавнего в одном приложении — это две правды о том, где человек
// был. Поэтому палитра читает список оболочки, а не свой: открытое где угодно
// видно и в меню, и в палитре.
//
// Команды палитра по-прежнему помнит сама: оболочка их не ведёт, и смешивать
// «куда ходил» с «что делал» незачем.
import type { KitShellApi, RecentList, SafeStorage } from '@seidr/kit';
import { createRecentList } from '@seidr/kit';

/**
 * Список недавнего для палитры поверх оболочки.
 *
 * Записи — из оболочки (её ведёт `openRecord`, и она же переживает
 * перезагрузку). Команды — в своём хранилище: их в оболочке нет.
 */
export function shellRecentList(api: Pick<KitShellApi, 'recent' | 'openRecord'>, storage: SafeStorage): RecentList {
  const commands = createRecentList(storage, { key: 'lore.v2.palette.commands' });
  return {
    list() {
      // Записи первыми: человек чаще возвращается к записи, чем повторяет команду.
      return [
        ...api.recent.map(id => `record:${id}` as const),
        ...commands.list().filter(k => k.startsWith('command:')),
      ];
    },
    push(item) {
      // Запись уходит в оболочку — туда же, откуда её берёт меню. Адрес и
      // название палитра не знает, поэтому пункт меню для такой записи
      // останется кнопкой, пока её не откроют из списка (там адрес есть).
      if (item.type === 'record') api.openRecord(item.id);
      else commands.push(item);
    },
  };
}
