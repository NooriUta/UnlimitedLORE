// Сверка «было = стало» на СТАРОЙ базе: момент в источнике записан с какой угодно точностью, а DATETIME ArcadeDB
// отдаёт миллисекунды. Найдено 22.11.2026 на прогоне установщика 1.18.2 (ryzenai, бэкап прода 01.11.2026):
// перенос записал всё (счёт сошёлся по всем типам), а сверка объявила расхождения в 1606 записях шести типов
// версий — KnowADRHist 370, KnowDecisionHist 158, KnowMilestoneHist 8, KnowReleaseHist 426, KnowRunbookHist 50,
// KnowSpecHist 594: «got 2026-06-11 13:51:37.000 · want 2026-06-11 13:51:37» и
// «got 2026-07-03 00:02:12.990 · want 2026-07-03 00:02:12.990148988». Значения равны, расходится запись.
import test from 'node:test';
import assert from 'node:assert/strict';
import { asRead } from './transfer.mjs';

test('DATETIME: ожидание сверки пишется так же, как база его отдаёт — миллисекунды', () => {
  // секунды (в бэкапе прода 01.11.2026 — 113 версий ADR, 158 решений, 8 вех, 74 релиза, 164 спеки)
  assert.equal(asRead('2026-06-11 13:51:37', 'DATETIME'), '2026-06-11 13:51:37.000');
  assert.equal(asRead('2026-06-11T13:51:37Z', 'DATETIME'), '2026-06-11 13:51:37.000');
  // наносекунды (Instant.toString() старых записей) — база хранит миллисекунды, лишнее отбрасывается
  assert.equal(asRead('2026-07-03 00:02:12.990148988', 'DATETIME'), '2026-07-03 00:02:12.990');
  assert.equal(asRead('2026-06-28T23:47:41.228809694Z', 'DATETIME'), '2026-06-28 23:47:41.228');
  // микросекунды и без секунд вовсе
  assert.equal(asRead('2026-06-11T13:51:37.123456Z', 'DATETIME'), '2026-06-11 13:51:37.123');
  assert.equal(asRead('2026-06-11 13:51', 'DATETIME'), '2026-06-11 13:51:00.000');
  // прежнее поведение не меняется
  assert.equal(asRead('2026-04-23', 'DATETIME'), '2026-04-23 00:00:00.000');
  assert.equal(asRead('2026-04-23T10:11:12.000Z', 'DATETIME'), '2026-04-23 10:11:12.000');
  assert.equal(asRead('2026-04-23', 'DATE'), '2026-04-23');
  assert.equal(asRead(5, 'LONG'), 5);
  // не момент — не трогаем: сверка должна показать настоящее расхождение, а не причесать его
  assert.equal(asRead('позже', 'DATETIME'), 'позже');
});
