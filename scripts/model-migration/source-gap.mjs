// Перенос на базу СТАРШЕ правил: «такого в источнике нет» — это не ошибка (SPRINT_LORE_MODEL_DOCS_TIDY/MIG-04,
// находки прогона установщика 22.11.2026).
//
// Повод. Правила переноса писались под свежий снимок нашего прода. На бэкапе от 01.11 три шага останавливали
// установку, хотя переносить было нечего: правило называло гейты, которых в той базе ещё не было; строка таблицы
// названий вела в проекты, которые тогда ещё не были слиты в группу; организация называла проект, которого в
// приёмнике нет. Это та же болезнь, что и «тип карты, которого нет в старом источнике» — шаг обязан сказать
// «такого нет, делать нечего» и НАЗВАТЬ это, а не падать.
//
// Что НЕ попадает под это послабление: расхождения, которые видны уже ПОСЛЕ записи (записали и не сошлось),
// и противоречия в самом правиле (две строки на один проект, проектный гейт без проекта). Они красные всегда.
//
// Строгий режим. Наша собственная труба гоняет перенос на свежем снимке прода, и там пропуск — настоящий
// дефект правила. Поэтому `LORE_MIGRATE_STRICT=1` (его ставит наш прогон) возвращает прежнее поведение:
// красным становится любой пропуск. У друга переменной нет — установка идёт и честно отчитывается.

/** Включён ли строгий режим (наша труба). Значение читается на каждый вызов — тесты меняют env. */
export function strictMode(env = process.env) {
  const v = env && env.LORE_MIGRATE_STRICT;
  return v === '1' || v === 'true' || v === 'yes';
}

/**
 * Разделить отклонения на «источник старше правила» (absent) и настоящие расхождения (mismatch).
 * kinds — виды, которые для этого шага означают «такого в источнике/приёмнике нет».
 */
export function splitGaps(problems, kinds, { strict = strictMode() } = {}) {
  const absentKinds = new Set(kinds);
  const absent = [], mismatch = [];
  for (const p of problems || []) (absentKinds.has(p && p.kind) ? absent : mismatch).push(p);
  return { absent, mismatch, blocking: strict ? [...mismatch, ...absent] : mismatch };
}

/**
 * Строка отчёта про пропущенное: называем поимённо, молчать нельзя.
 * title — общая причина шага; когда у пропусков причины РАЗНЫЕ (гейта нет в источнике / у гейта нет проекта),
 * шаг передаёт нейтральное «делать нечего», а причину несёт сам пункт.
 */
export function gapLine(absent, describe = p => p.kind, title = 'нет в источнике (пропущено, не ошибка)') {
  if (!absent.length) return '';
  return `; ${title}: ${absent.map(describe).join(', ')}`;
}
