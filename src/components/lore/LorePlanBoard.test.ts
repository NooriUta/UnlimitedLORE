import { describe, expect, it } from 'vitest';
import canonical from '../../../shared/lore-statuses.json';
import { STATUS_ORDER } from './LorePlanBoard';

/**
 * Порядок статусов на доске плана обязан быть ПЕРЕСТАНОВКОЙ канона.
 *
 * Канон задаёт СОСТАВ (что вообще может быть записано), доска задаёт ПОРЯДОК
 * показа — это разные вопросы, и порядок канон не описывает. Но состав обязан
 * совпадать, иначе расхождение молчит в обе стороны:
 *
 *  • лишнее значение никогда не совпадёт ни с одним спринтом и просто не
 *    покажется — выглядит как «таких спринтов нет»;
 *  • пропущенное значение выкидывает ЗАКОННЫЙ статус из легенды: спринт в нём
 *    исчезает с доски, и это неотличимо от того, что его не завели.
 *
 * Оба случая жили здесь до 30.08.2026 одновременно: список нёс `deferred`
 * (статус вопроса, не спринта) и терял `ready_for_deploy`. Ни один не краснел.
 */
describe('LorePlanBoard · порядок статусов', () => {
  it('состав совпадает с каноном planStatuses', () => {
    expect([...STATUS_ORDER].sort()).toEqual([...canonical.planStatuses].sort());
  });

  it('без повторов — иначе столбец нарисуется дважды', () => {
    expect(new Set(STATUS_ORDER).size).toBe(STATUS_ORDER.length);
  });
});
