// «Ещё» решает РЯД ВКЛАДОК, а не модель (паспорта v3, 10.11.2026,
// D-2026-UXR-OWNER-DELEGATED-ANSWERS-10-11).
//
// Что поменялось и почему. До сегодня «под Ещё» приходило из модели
// (`slot: more`). Это было решение о ЧУЖОМ ЭКРАНЕ, принятое вслепую: сервер не
// знает ни ширины окна, ни масштаба текста, ни того, сколько вкладок у этой
// записи вообще набралось. Поэтому `more` убран, а правило переехало сюда:
// первые по порядку — в ряд, сколько влезает по ширине, но НЕ БОЛЬШЕ СЕМИ;
// остальное — под «Ещё».
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, А ЧТО НЕТ — честно, без притворства.
// jsdom раскладку не считает: у любого элемента ширина 0, и «влезает ли» в нём
// не измерить. Поэтому правило разложено на две части:
//   • ПРОВЕРЯЕМОЕ (здесь): потолок 7, порядок по месту в списке, уход с КОНЦА
//     (а не перетасовка), выбранная вкладка в ряду всегда;
//   • ИЗМЕРЯЕМОЕ (не здесь): сколько чипов влезло в конкретную ширину. Его
//     считает браузер, и Tabs отдаёт сюда уже готовое число `fits`. Поэтому
//     здесь `fits` передаётся руками: функция чистая, и за «влезает» она не
//     отвечает.
// Разделение не косметическое: «потолок 7» и «уходит с конца» — это и есть то,
// что владелица просила («интерфейс становится перегруженным»), и именно это
// можно удержать тестом без браузера.
import { describe, expect, it } from 'vitest';
import { TAB_ROW_MAX, foldRow } from './tabRow';

const item = (id: string) => ({ id });
/** Девять вкладок: больше потолка, чтобы потолок было видно. */
const nine = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h', 'i'].map(item);

describe('ряд вкладок: потолок семь', () => {
  it('положительный контроль: потолок назван числом, а не спрятан в вёрстке', () => {
    expect(TAB_ROW_MAX).toBe(7);
  });

  it('вкладок меньше потолка — все в ряду, свёртки нет', () => {
    const r = foldRow(nine.slice(0, 5), 'a');
    expect(r.shown.map(i => i.id)).toEqual(['a', 'b', 'c', 'd', 'e']);
    expect(r.folded).toEqual([]);
  });

  it('ровно семь — все в ряду: потолок не «шесть и Ещё»', () => {
    const r = foldRow(nine.slice(0, 7), 'a');
    expect(r.shown).toHaveLength(7);
    expect(r.folded).toEqual([]);
  });

  it('больше семи — в ряду семь, остальное под «Ещё»', () => {
    const r = foldRow(nine, 'a');
    expect(r.shown).toHaveLength(7);
    expect(r.folded.map(i => i.id)).toEqual(['h', 'i']);
  });

  it('уходят с КОНЦА, а порядок остатка прежний — ряд не перетасовывается', () => {
    // Это и есть «порядок по смыслу одинаков на любой ширине»: сужая окно,
    // человек видит, как последние вкладки уезжают под «Ещё», а не как ряд
    // пересобирается в другом порядке.
    expect(foldRow(nine, 'a', 4).shown.map(i => i.id)).toEqual(['a', 'b', 'c', 'd']);
    expect(foldRow(nine, 'a', 2).shown.map(i => i.id)).toEqual(['a', 'b']);
    expect(foldRow(nine, 'a', 2).folded.map(i => i.id)).toEqual(['c', 'd', 'e', 'f', 'g', 'h', 'i']);
  });

  it('что влезло по ширине — главнее потолка, но потолок его не повышает', () => {
    // `fits` приходит из браузера. Он может быть меньше семи (узко) — тогда
    // ряд короче; больше семи он быть не может даже на широком экране.
    expect(foldRow(nine, 'a', 99).shown).toHaveLength(7);
    expect(foldRow(nine, 'a', 3).shown).toHaveLength(3);
  });

  it('ряд не бывает пустым: даже при нулевой ширине остаётся одна вкладка', () => {
    // Иначе на узком экране человек получил бы ряд из одной кнопки «Ещё» и
    // перестал понимать, где находится.
    const r = foldRow(nine, 'c', 0);
    expect(r.shown.map(i => i.id)).toEqual(['c']);
  });
});

describe('ряд вкладок: выбранная не прячется никогда', () => {
  it('выбранная за потолком всё равно в ряду, и ряд не перерос потолок', () => {
    const r = foldRow(nine, 'i');
    expect(r.shown.map(i => i.id)).toContain('i');
    expect(r.shown).toHaveLength(TAB_ROW_MAX);
    // Место ей освободила ПОСЛЕДНЯЯ из влезавших, а не перестановка: голова
    // ряда осталась прежней.
    expect(r.shown.map(i => i.id)).toEqual(['a', 'b', 'c', 'd', 'e', 'f', 'i']);
  });

  it('выбранная стоит на своём месте, а не прыгает в начало ряда', () => {
    const r = foldRow(nine, 'h', 3);
    expect(r.shown.map(i => i.id)).toEqual(['a', 'b', 'h']);
  });

  it('выбранной в списке нет (адрес из прошлой записи) — ряд заполняется с головы', () => {
    const r = foldRow(nine, 'zzz', 3);
    expect(r.shown.map(i => i.id)).toEqual(['a', 'b', 'c']);
  });
});

describe('ряд вкладок: признак «редкая» от приложения остаётся', () => {
  const marked = [
    { id: 'a' },
    { id: 'b', secondary: true },
    { id: 'c' },
  ];

  it('помеченная приложением уходит под «Ещё» и при свободном месте', () => {
    // Признак даёт приложение (у LORE — личная настройка человека). Потолок
    // про перегруженность, а этот признак — про «мне это не нужно в ряду»;
    // смешивать их нельзя, иначе личная настройка пропадёт на широком экране.
    const r = foldRow(marked, 'a');
    expect(r.shown.map(i => i.id)).toEqual(['a', 'c']);
    expect(r.folded.map(i => i.id)).toEqual(['b']);
  });

  it('но ВЫБРАННАЯ помеченная — в ряду: прятать читаемое нельзя', () => {
    const r = foldRow(marked, 'b');
    expect(r.shown.map(i => i.id)).toEqual(['a', 'b', 'c']);
    expect(r.folded).toEqual([]);
  });
});

describe('ряд вкладок: функция чистая', () => {
  it('исходный список не портится и не переупорядочивается на месте', () => {
    const copy = nine.map(i => ({ ...i }));
    foldRow(nine, 'i', 3);
    expect(nine).toEqual(copy);
  });

  it('shown и folded вместе дают весь список, без потерь и без дублей', () => {
    for (const fits of [0, 1, 3, 7, 99]) {
      const r = foldRow(nine, 'e', fits);
      expect([...r.shown, ...r.folded].map(i => i.id).sort()).toEqual(nine.map(i => i.id).sort());
    }
  });
});
