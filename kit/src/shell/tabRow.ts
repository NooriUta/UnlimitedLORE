// Ряд вкладок: один ключ — одна вкладка (ревью 10.11.2026, B13 + просьба
// владелицы того же дня: «проверить, почему, например, в паспорте у спринтов
// дублирующиеся вкладки»).
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО ЗДЕСЬ НЕТ. Здесь — уникальность ключей ряда, то есть
// чистая ФОРМА: ряд склеивается из нескольких списков, и совпавший ключ
// означает один раздел, а не два. Здесь НЕТ приоритета «что важнее» и «что
// уходит под Ещё»: порядок и второстепенность приходят из модели
// (`surfaces.passport.<type>.sections`, разбор — model/surfaces.ts; `slot:
// more` и есть «под Ещё»), а kit их только раскладывает. Своё правило
// приоритета в конструкторе было бы ВТОРОЙ правдой о порядке: у типа, которому
// сервер порядок уже задал, оно разошлось бы с моделью молча.

/**
 * Один ключ — одна вкладка.
 *
 * Ряд склеивается из разных списков: вкладки вида от приложения, вкладки связей
 * от kit, служебное вокруг записи. Ключи у них совпадают, и совпадают
 * ЗАКОННО: в LORE «Задачи» спринта приходят И вкладкой вида с настоящей
 * таблицей, И связью-композицией, по которой считается число и рисуется значок
 * ◆. До этой сверки склейка шла конкатенацией, и в ряду оказывались две вкладки
 * с одним id и одной подписью — одна со счётчиком, другая без (ровно
 * «дублирующиеся вкладки» и «счётчики то есть, то нет» из ревью).
 *
 * Слияние, а не выбрасывание: первая вкладка задаёт место, подпись и
 * содержимое (её объявили намеренно и раньше), а всё, чего у неё нет — счётчик,
 * значок вида связи, иконку, — добирает у двойника. Так с экрана не исчезает ни
 * содержимое, ни число.
 */
export function mergeTabs<T extends { id: string }>(items: readonly T[]): T[] {
  const out: T[] = [];
  const at = new Map<string, number>();
  for (const item of items) {
    const i = at.get(item.id);
    if (i === undefined) { at.set(item.id, out.length); out.push(item); continue; }
    const first = { ...out[i] } as Record<string, unknown>;
    for (const [k, v] of Object.entries(item as Record<string, unknown>)) {
      if (first[k] === undefined && v !== undefined) first[k] = v;
    }
    out[i] = first as T;
  }
  return out;
}
