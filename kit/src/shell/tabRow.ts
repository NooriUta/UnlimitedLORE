// Ряд вкладок: один ключ — одна вкладка (ревью 10.11.2026, B13 + просьба
// владелицы того же дня: «проверить, почему, например, в паспорте у спринтов
// дублирующиеся вкладки»).
//
// ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО ЗДЕСЬ НЕТ. Здесь — чистая ФОРМА ряда: уникальность
// ключей (ряд склеивается из нескольких списков, и совпавший ключ означает
// один раздел, а не два) и то, сколько вкладок ряд вмещает. Здесь НЕТ
// ПРИОРИТЕТА «что важнее»: порядок разделов приходит из модели
// (`surfaces.passport.<type>.sections`, разбор — model/surfaces.ts), и свой
// приоритет в конструкторе был бы ВТОРОЙ правдой о порядке — у типа, которому
// сервер порядок уже задал, он разошёлся бы с моделью молча.
//
// А ВОТ «ЧТО УХОДИТ ПОД ЕЩЁ» — ИМЕННО ЗДЕСЬ, и это смена хозяина (паспорта v3,
// 10.11.2026). Раньше это решала модель значением `slot: more`. Решение
// оказалось принятым вслепую: сервер не знает ни ширины окна, ни масштаба
// текста, ни того, сколько вкладок у записи набралось вместе со служебными.
// Поэтому `more` из контракта убран, а правило стало правилом формы: первые по
// порядку — в ряд, сколько влезает, но не больше потолка; остальное — под
// «Ещё». Порядок при этом НЕ МЕНЯЕТСЯ: сужая окно, человек видит, как
// последние вкладки уезжают под свёртку, а не как ряд пересобирается заново.

/**
 * Один ключ — одна вкладка.
 *
 * Ряд склеивается из разных списков: вкладки вида от приложения, вкладки связей
 * от kit, служебное вокруг записи. Ключи у них совпадают, и совпадают
 * ЗАКОННО: в LORE «Задачи» спринта приходят И вкладкой вида с настоящей
 * таблицей, И связью-композицией, по которой считается число и рисуется значок
 * ◆. До этой сверки склейка шла конкатенацией, и в ряду оказывались две вкладки
 * с одним id и одной подписью — одна со счётчиком, другая без (ровно
 * «дублирующиеся вкладки» и «счётчики то есть, то нет» из ревью).
 *
 * Слияние, а не выбрасывание: первая вкладка задаёт место, подпись и
 * содержимое (её объявили намеренно и раньше), а всё, чего у неё нет — счётчик,
 * значок вида связи, иконку, — добирает у двойника. Так с экрана не исчезает ни
 * содержимое, ни число.
 */
export function mergeTabs<T extends { id: string }>(items: readonly T[]): T[] {
  const out: T[] = [];
  const at = new Map<string, number>();
  for (const item of items) {
    const i = at.get(item.id);
    if (i === undefined) { at.set(item.id, out.length); out.push(item); continue; }
    const first = { ...out[i] } as Record<string, unknown>;
    for (const [k, v] of Object.entries(item as Record<string, unknown>)) {
      if (first[k] === undefined && v !== undefined) first[k] = v;
    }
    out[i] = first as T;
  }
  return out;
}

/**
 * Потолок ряда: СЕМЬ вкладок, сколько бы ни было места.
 *
 * Повод — слова владелицы 09.11.2026: «интерфейс становится перегруженным».
 * Потолок именно числом, а не «пока влезает»: на широком мониторе влезает
 * пятнадцать, и ряд из пятнадцати чипов перестаёт читаться задолго до того,
 * как кончится ширина. Ширина отвечает за узкий экран, потолок — за широкий.
 */
export const TAB_ROW_MAX = 7;

/** Как ряд разошёлся: что в ряду, что под свёрткой «Ещё». */
export interface FoldedRow<T> { shown: T[]; folded: T[] }

/**
 * Разложить ряд: первые по порядку — в ряд, остальное — под «Ещё».
 *
 * `fits` — сколько чипов влезло ПО ШИРИНЕ; его считает браузер и передаёт
 * Tabs. Здесь его не измеряют и не угадывают: функция чистая, поэтому правило
 * («потолок семь», «уходит с конца», «выбранная в ряду») проверяется тестом
 * без браузера, а неизмеримое в jsdom остаётся снаружи. По умолчанию ширина не
 * ограничивает — работает один потолок.
 *
 * Три правила, и порядок между ними важен:
 *  1. ВЫБРАННАЯ вкладка в ряду ВСЕГДА, даже за потолком и даже помеченная
 *     редкой: спрятать то, что человек сейчас читает, хуже перегруженности —
 *     он перестаёт понимать, где находится. Место ей освобождает последняя из
 *     влезавших, поэтому потолок не растёт.
 *  2. `secondary` от приложения — личный выбор человека («мне это в ряду не
 *     нужно»), и он действует даже когда места вдоволь. Смешать его с потолком
 *     значило бы терять личную настройку на широком экране.
 *  3. Остальное — по порядку с головы, пока есть места. Уход именно С КОНЦА:
 *     ряд не пересобирается, он укорачивается.
 *
 * Ряд никогда не бывает пустым: при нулевой ширине остаётся одна вкладка —
 * иначе на телефоне человек получил бы ряд из одной кнопки «Ещё».
 */
export function foldRow<T extends { id: string; secondary?: boolean }>(
  items: readonly T[],
  value: string,
  fits: number = TAB_ROW_MAX,
): FoldedRow<T> {
  const budget = Math.max(1, Math.min(Math.floor(fits), TAB_ROW_MAX));
  const keep = new Set<string>();
  const selected = items.find(i => i.id === value);
  if (selected) keep.add(selected.id);
  let room = budget - keep.size;
  for (const i of items) {
    if (room <= 0) break;
    if (keep.has(i.id) || i.secondary) continue;
    keep.add(i.id);
    room--;
  }
  return {
    shown: items.filter(i => keep.has(i.id)),
    folded: items.filter(i => !keep.has(i.id)),
  };
}
