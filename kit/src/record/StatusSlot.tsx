// Статус записи: плашка или кнопка — по правам
// (SPRINT_UXR_S4_UI_SHELL_LISTS/S4-STATUS-AXIS-CONFIG, дефект 09.11).
//
// До этого в записи статус рисовался ТОЛЬКО плашкой (`StatusPill`) — и в
// шапке, и в строке фактов. То есть сменить статус из паспорта было нельзя
// нигде и ни у какого типа: кнопки не существовало. Замечание владелицы («не
// могу поменять статус адр через новый редиз») указало на ADR, но причина была
// общая.
//
// Почему это место в kit, а не в приложении: «статус меняется, когда права
// позволяют» — ФОРМА, одинаковая для любого приложения на конструкторе. Что за
// права у человека и куда уходит сохранение, решает приложение
// (`config.roles`, `hooks.onSave`); kit только выбирает между плашкой и
// кнопкой. Это тот же водораздел, что в K-14.
//
// Обратное закреплено не менее твёрдо: без прав кнопка НЕ появляется, а
// значение всё равно видно. Кнопка, которая отказывает при нажатии, хуже её
// отсутствия; а «нет прав» не повод скрывать сам статус.
import { StatusChip } from '../core/StatusChip';
import { canChangeStatus } from '../core/statusModel';
import type { KitCtx, KitRecord } from '../core/contract';
import { StatusPill } from './fmt';

export function StatusSlot({ record, ctx, unknownTitle, compact }: {
  record: KitRecord;
  ctx: KitCtx;
  /** Подпись для статуса вне словаря — её даёт вызывающий (у него свой язык). */
  unknownTitle: string;
  /** Плотная строка (строка фактов): только иконка, имя остаётся для чтения. */
  compact?: boolean;
}) {
  // Пустая статусная ось (K-14) — у типа статуса нет вовсе, и менять нечего.
  // Проверяется ДО прав: право сменить то, чего не существует, бессмысленно.
  const hasAxis = (ctx.config.statuses?.items?.length ?? 0) > 0;
  // Пустой код — чип не рисуем ни плашкой, ни кнопкой (B5): показывать нечего,
  // а «—» у типа без статуса читалось как реальный статус записи.
  if (!hasAxis || !record.status) return null;
  if (!canChangeStatus(ctx.config, ctx.role)) {
    return <StatusPill code={record.status} ctx={ctx} unknownTitle={unknownTitle} />;
  }
  // Обёртка с тем же классом, что у плашки (`sk-rec-status`), — НАМЕРЕННО:
  // «статус в статье показан один раз» и порядок элементов шапки проверяются
  // по этому признаку, и он не должен зависеть от того, плашка сейчас или
  // кнопка. Без обёртки две проверки раскладки покраснели бы не потому, что
  // раскладка сломалась, а потому что сменился вариант узла.
  return (
    <span className="sk-rec-status">
    <StatusChip record={record} config={ctx.config} role={ctx.role}
      // Клавиша S — в записи (в списке она выключена): здесь запись одна, и
      // «S → цифра» это обещанные два касания (K-05).
      hotkey
      // Завершающие статусы третьим шагом (S4-07): случайное «готово» дорого.
      confirmFinal
      {...(compact ? { compact: true } : {})} />
    </span>
  );
}
