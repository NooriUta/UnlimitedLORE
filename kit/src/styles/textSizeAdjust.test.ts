// Браузер телефона НЕ раздувает наш текст сам (находка со снимка владелицы
// 10.11.2026: «все еще не адаптивно под телефон», new.lore на Android).
//
// Что было видно на снимке: в браузере телефона кегли и обвязка примерно
// ВДВОЕ больше наших токенов — чип фильтра занимал около сотни пикселей при
// подписи в 11 px по шкале. Наши собственные размеры такого дать не могут:
// `--tap` растит высоту до 44 px, а не до сотни, и кегль он не трогает вовсе.
//
// Причина — автоувеличение текста в движке (text autosizing / font boosting):
// браузеры Android увеличивают шрифт в блоках, которые считают «немобильными»,
// и делают это ПОСЛЕ применения наших стилей. Отключается одним свойством, и
// в корпусе его не было ни разу (проверено грепом 10.11.2026).
//
// Почему это правило, а не правка одного экрана: свойство наследуется от корня
// и действует на всё приложение; поставив его на один блок, мы получили бы
// разъехавшиеся экраны — часть в наших размерах, часть в умноженных.
//
// Что это НЕ отменяет: масштаб страницы, который человек задал сам (щипком или
// настройкой браузера), остаётся — `text-size-adjust` управляет только
// самовольным увеличением шрифта движком.
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const css = readFileSync(join(process.cwd(), 'src/styles/seidr.css'), 'utf8');

/** Тело правила по селектору (первое вхождение). */
function rule(selector: string): string {
  const i = css.indexOf(`${selector} {`);
  expect(i, `правила ${selector} в seidr.css нет — поправьте сторож`).toBeGreaterThan(-1);
  return css.slice(css.indexOf('{', i) + 1, css.indexOf('}', i));
}

describe('движок телефона не увеличивает наш текст сам', () => {
  it('положительный контроль: файл прочитан и корневое правило найдено', () => {
    expect(css.length).toBeGreaterThan(1000);
    expect(rule(':root')).toContain('--fs-base');
  });

  it('свойство стоит и выключает самовольное увеличение', () => {
    const body = rule('html');
    expect(body, 'без text-size-adjust Android раздувает шрифты поверх наших токенов')
      .toMatch(/(^|[^-])text-size-adjust:\s*100%/);
  });

  it('стоит и префиксная запись — её понимают Safari и браузеры Android', () => {
    expect(rule('html')).toMatch(/-webkit-text-size-adjust:\s*100%/);
  });

  it('значение именно 100%, а не none: «none» ломает масштаб у слабовидящих', () => {
    expect(rule('html')).not.toMatch(/text-size-adjust:\s*none/);
  });
});
