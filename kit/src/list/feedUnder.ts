// Нижний уровень двухуровневой ленты: что показать и что предложить
// (SPRINT_UXR_S10_SEIDR_KIT_2/K2-FEED-TWO-LEVEL, spec:SPEC-LORE-KIT-FEED-VIEW §4).
//
// Просьба владелицы 09.11.2026: «раздели еще одну идею … дерево будет двух
// уровневая лента» — верхний уровень полосой, под ним то, что в нём двигалось.
//
// ОТКРЫТЫЙ ВОПРОС СПЕКИ ЗАКРЫТ. Спрашивали: грузить нижний уровень при
// раскрытии или сразу вместе с верхним. Владелица 10.11.2026 ответила по телу
// записи в ленте дословно: «нет в feed грузить первые 3 абзаца остально при
// расеррытии», и это же правило распространила на нижний уровень — ГРУЗИТЬ ПРИ
// РАСКРЫТИИ. Значит это требование, а не допущение: сразу — N запросов на один
// экран, по одному на каждую полосу.
//
// Отсюда ПЯТЬ состояний нижнего уровня, и у каждого своё предложение под
// полосой:
//   • не загружен        → запросить («Ещё N»);
//   • пришёл             → раскрыть на месте, без похода в сеть;
//   • едет               → сказать «идёт» и не предлагать второй раз;
//   • не дошёл           → назвать причину и предложить повтор;
//   • нет прав           → назвать причину и НЕ предлагать повтор: повторять
//                          нечего, чинится это не повтором.
// Один вид на все пять врал бы трижды: обещал бы мгновенное раскрытие там, где
// будет запрос; ходил бы в сеть за тем, что уже лежит рядом; и предлагал бы
// «попробовать снова» тому, кому просто не дали смотреть.
//
// Правило живёт чистой функцией, а не разметкой, потому что это утверждения о
// состоянии, а не вид: «не загрузили» ≠ «пусто» ≠ «нет прав» ≠ «показано не
// всё». Тот же приём, что у `foldBody` (K2-FEED-BODY-MORE).
//
// Чего здесь НЕТ намеренно: знания о том, ЧТО такое верхний и нижний уровень.
// Это предметное знание приложения (водораздел K-14): kit получает состояние
// названным, а подпись уровня — из конфига (`list.feed.under.title`).
import type { KitRecord } from '../core/contract';

/**
 * Состояние нижнего уровня, которое НАЗЫВАЕТ приложение.
 *
 * `rest` — нижний уровень ещё в источнике (умолчание до раскрытия); `count` —
 * сколько там, `null` — числа не назвали. `here` — записи пришли; пустой
 * список здесь это ПРОВЕРЕННЫЙ ноль, а `total` больше числа записей —
 * «показано не всё». `loading` — запрошен. `failed` / `forbidden` — не дошёл и
 * не дадут: два РАЗНЫХ исхода, и лечатся они по-разному.
 *
 * Глубже двух уровней договор не идёт: `here` отдаёт ЗАПИСИ, а не ещё одну
 * такую же свёртку. Просьба была про два уровня, а дерево неизвестной глубины
 * в ленте читается хуже таблицы.
 */
export type FeedUnder =
  | { kind: 'rest'; count: number | null }
  | { kind: 'here'; records: readonly KitRecord[]; total?: number }
  | { kind: 'loading' }
  | { kind: 'failed'; reason: string }
  | { kind: 'forbidden'; reason: string };

/** Что предлагать под полосой верхнего уровня. Пять состояний — пять разных предложений. */
export type FeedUnderAction =
  /** Предлагать нечего: либо нижнего уровня у записи нет, либо он проверенно пуст. */
  | { kind: 'none' }
  /** Нижний уровень в источнике: запросить. `n` null — числа не назвали. */
  | { kind: 'load'; n: number | null }
  /** Пришёл и свёрнут: раскрыть на месте. */
  | { kind: 'open'; n: number }
  /** Раскрыт: свернуть обратно. */
  | { kind: 'close' }
  /** Едет. */
  | { kind: 'busy' }
  /** Не дошёл, причина словами — повтор уместен. */
  | { kind: 'retry'; reason: string }
  /** Нет прав, причина словами — повтор НЕ уместен. */
  | { kind: 'denied'; reason: string };

export interface FeedUnderFold {
  /** Записи нижнего уровня, которые видно сейчас. */
  rows: readonly KitRecord[];
  action: FeedUnderAction;
  /**
   * Источник ответил, и в верхнем уровне правда ничего нет. Утверждение, а не
   * пустое место: «не загрузили» выглядело бы так же, а значит иначе.
   */
  nothing: boolean;
  /** Пришло не всё: показано `shown` из `total`. Не названо — не утверждаем. */
  cut: { shown: number; total: number } | null;
}

/** Число, на которое можно сослаться в «Ещё N»; мусор — «числа не назвали». */
function countOf(n: number | null): number | null {
  if (n === null || !Number.isInteger(n) || n < 0) return null;
  return n;
}

/**
 * Свёртка нижнего уровня: что видно и что предлагать.
 *
 * `expanded` влияет только на ВИДИМЫЕ строки — предложение зависит от
 * состояния нижнего уровня. Поэтому у раскрытой записи с незагруженным нижним
 * уровнем предложение остаётся «запросить»: раскрыто — да, присылали — нет.
 */
export function foldUnder(under: FeedUnder | null, expanded: boolean): FeedUnderFold {
  const empty: FeedUnderFold = { rows: [], action: { kind: 'none' }, nothing: false, cut: null };
  // Запись не верхнего уровня: предлагать нечего, и это НЕ «пусто» — про её
  // нижний уровень мы ничего не утверждаем, его просто не бывает.
  if (!under) return empty;

  switch (under.kind) {
    case 'loading':
      return { ...empty, action: { kind: 'busy' } };
    case 'failed':
      return { ...empty, action: { kind: 'retry', reason: under.reason } };
    case 'forbidden':
      // «Нет прав» не выдаёт себя за «ничего нет»: nothing остаётся false.
      return { ...empty, action: { kind: 'denied', reason: under.reason } };
    case 'rest': {
      const n = countOf(under.count);
      // Ноль, названный источником БЕЗ загрузки, — тоже проверенный ноль:
      // источник сказал «там ничего», и ходить за этим незачем.
      if (n === 0) return { ...empty, nothing: true };
      return { ...empty, action: { kind: 'load', n } };
    }
    case 'here': {
      const rows = under.records;
      const total = under.total;
      // Итог меньше числа пришедших строк — не верим и обрезку не выдумываем:
      // ложное «показаны 3 из 2» хуже отсутствующей оговорки.
      const cut = typeof total === 'number' && Number.isFinite(total) && total > rows.length
        ? { shown: rows.length, total }
        : null;
      if (rows.length === 0) return { ...empty, nothing: true, cut };
      return {
        rows: expanded ? rows : [],
        action: expanded ? { kind: 'close' } : { kind: 'open', n: rows.length },
        nothing: false,
        cut,
      };
    }
  }
}
