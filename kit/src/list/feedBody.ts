// Тело записи в ленте: первые абзацы и остаток при раскрытии
// (SPRINT_UXR_S10_SEIDR_KIT_2/K2-FEED-BODY-MORE, spec:SPEC-LORE-KIT-FEED-VIEW §5).
//
// Решение владелицы 10.11.2026, дословно: «нет в feed грузить первые 3 абзаца
// остально при расеррытии». Моё прежнее допущение «два абзаца» снято.
//
// Слово «грузить» здесь главное. Остаток не просто спрятан — его ЕЩЁ НЕТ:
// лента из десяти ADR, тянущая полные тела, это десять документов на один
// экран. Отсюда ЧЕТЫРЕ состояния остатка, и у каждого своё предложение под
// телом:
//   • остаток не загружен → запросить («Ещё N»);
//   • остаток здесь, но скрыт → раскрыть на месте, без похода в сеть;
//   • остаток едет → сказать «идёт» и не предлагать второй раз;
//   • остаток не дошёл → назвать причину и предложить повтор.
// Один вид на все четыре врал бы дважды: обещал бы мгновенное раскрытие там,
// где будет запрос, и ходил бы в сеть за тем, что уже лежит рядом.
//
// Чего здесь НЕТ намеренно: разбора текста на абзацы. Что считать абзацем в
// теле (и чем его резать) — предметное знание и забота источника, который
// начало и отдаёт (K-14). kit получает абзацы готовыми, названными.

/**
 * Сколько абзацев видно в свёрнутом теле. Число владелицы: «первые 3 абзаца».
 *
 * Названо ОДНИМ местом: повторённое в вёрстке и в тесте, оно разошлось бы при
 * первой же правке, и экран перестал бы совпадать с договором.
 */
export const FEED_BODY_PARAGRAPHS = 3;

/**
 * Тело записи для ленты — состояние, которое НАЗЫВАЕТ приложение.
 *
 * `head` — пришло начало, остаток лежит в источнике; `full` — тело целиком
 * здесь; `loading` — остаток запрошен; `failed` — остаток не дошёл, и причина
 * названа словами.
 *
 * Абзацы есть у всех четырёх: начало, которое уже пришло, не исчезает ни во
 * время запроса, ни после сбоя. Исчезающий текст читается как «тела нет».
 */
export type FeedBody = FeedBodyState & {
  /**
   * Подпись раздела, из которого взято тело (владелица 11.11.2026: «лента —
   * лента паспортов», раздел «Контекст», у типа без него — первый раздел тела).
   * Задана — тело рисуется разделом паспорта с этой подписью. Не задана —
   * подписи нет: выдумывать её kit не станет (K-14).
   */
  section?: string;
};

export type FeedBodyState =
  | {
      kind: 'head';
      paragraphs: readonly string[];
      /**
       * Сколько абзацев ещё в источнике. `null` — приложение числа не назвало;
       * тогда «Ещё» идёт БЕЗ числа, и это сказано. Своё число kit не
       * придумывает: за «Ещё 4» человек ждёт четыре абзаца, а не сорок.
       */
      restCount: number | null;
    }
  | { kind: 'full'; paragraphs: readonly string[] }
  | { kind: 'loading'; paragraphs: readonly string[] }
  | { kind: 'failed'; paragraphs: readonly string[]; reason: string };

/** Что предлагать под свёрнутым телом. Четыре состояния остатка — четыре разных предложения. */
export type FeedBodyAction =
  /** Предлагать нечего: тело всё на экране. */
  | { kind: 'none' }
  /** Остаток в источнике: запросить. `n` null — числа не назвали. */
  | { kind: 'load'; n: number | null }
  /** Остаток здесь: раскрыть на месте. */
  | { kind: 'open'; n: number }
  /** Раскрыто и всё здесь: свернуть обратно. */
  | { kind: 'close' }
  /** Остаток едет. */
  | { kind: 'busy' }
  /** Остаток не дошёл, причина словами. */
  | { kind: 'retry'; reason: string };

export interface FeedBodyFold {
  /** Абзацы, которые видно сейчас. */
  shown: readonly string[];
  action: FeedBodyAction;
}

/**
 * Свёртка тела: что видно и что предлагать.
 *
 * `expanded` влияет ТОЛЬКО на видимые абзацы — предложение зависит от
 * состояния остатка. Поэтому у записи с незагруженным остатком «Ещё» остаётся
 * и после раскрытия: местное показали, серверное ещё не пришло.
 *
 * Потолок — параметр с умолчанием, а не вшитое число: правило одно, а
 * проверить его на другом числе иначе нельзя. Потолок ниже одного абзаца
 * приводится к одному: спрятать тело ЦЕЛИКОМ — это не свёртка, а пропажа
 * текста, и человек не поймёт, что под «Ещё» вообще что-то есть.
 */
export function foldBody(
  body: FeedBody | null,
  expanded: boolean,
  cap: number = FEED_BODY_PARAGRAPHS,
): FeedBodyFold {
  if (!body) return { shown: [], action: { kind: 'none' } };
  const limit = Math.max(1, Math.floor(cap));
  const all = body.paragraphs;
  const shown = expanded ? all : all.slice(0, limit);
  // Абзацы, которые уже пришли, но в свёрнутом виде не показаны.
  const local = Math.max(0, all.length - limit);

  if (body.kind === 'loading') return { shown, action: { kind: 'busy' } };
  if (body.kind === 'failed') return { shown, action: { kind: 'retry', reason: body.reason } };

  if (body.kind === 'full') {
    if (local === 0) return { shown, action: { kind: 'none' } };
    return { shown, action: expanded ? { kind: 'close' } : { kind: 'open', n: local } };
  }

  // kind === 'head': остаток в источнике. Скрытое местное считается в ТОТ ЖЕ
  // остаток — иначе кнопка обещала бы меньше, чем под ней лежит.
  const rest = body.restCount;
  if (rest === 0 && local === 0) return { shown, action: { kind: 'none' } };
  if (rest === 0) return { shown, action: expanded ? { kind: 'close' } : { kind: 'open', n: local } };
  return { shown, action: { kind: 'load', n: rest === null ? null : rest + local } };
}
