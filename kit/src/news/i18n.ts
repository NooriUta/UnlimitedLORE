const DICTS: Record<KitLang, Record<NewsKey, string>> = { ru, en };

export function newsDict(lang: KitLang): Record<NewsKey, string> {
  return DICTS[lang] ?? DICTS.ru;
}

export function newsT(lang: KitLang, key: NewsKey, vars?: Record<string, string | number>): string {
  const s = newsDict(lang)[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
